"""
Embed a subset TTF font into a C source file (stdlib only, no third-party deps).

Usage: python scripts/embed_font_data.py <input.ttf> <output.c>

The generated file defines:
    #define CJK_FONT_DATA_SIZE <bytes>
    const unsigned char cjkFontData[CJK_FONT_DATA_SIZE] = { ... };

This is the offline path used by CMake: the subset TTF is tracked in
src/fonts/cjk_subset.ttf, so a fresh clone does not need network access or
pip packages. To re-subset the font from Sarasa Gothic (needs network +
requests/py7zr/fonttools), use scripts/prepare_cjk_font.py instead.
"""

import os
import sys

BYTES_PER_LINE = 12
HEADER = """\
/**********************************************************************************************
*
*   cjk_font_data.c - Embedded CJK font data for raylib default font
*
*   AUTO-GENERATED by scripts/embed_font_data.py - DO NOT EDIT
*   Source font: src/fonts/cjk_subset.ttf
*   Original: Sarasa Gothic SC Regular (SIL OFL 1.1 license)
*   https://github.com/be5invis/Sarasa-Gothic
*
*   LICENSE: zlib/libpng (same as raylib)
*   The embedded font is licensed under SIL Open Font License 1.1
*
**********************************************************************************************/

"""


def embed(input_path, output_path):
    with open(input_path, "rb") as f:
        data = f.read()

    size = len(data)
    if size == 0:
        raise SystemExit("input font is empty: %s" % input_path)

    lines = [HEADER]
    lines.append("#define CJK_FONT_DATA_SIZE %d\n\n" % size)
    lines.append("const unsigned char cjkFontData[CJK_FONT_DATA_SIZE] = {\n")
    for start in range(0, size, BYTES_PER_LINE):
        chunk = data[start:start + BYTES_PER_LINE]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk) + ",\n")
    lines.append("};\n")

    tmp_path = output_path + ".tmp"
    with open(tmp_path, "w", newline="\n") as f:
        f.writelines(lines)
    os.replace(tmp_path, output_path)
    print("embedded %d bytes -> %s" % (size, output_path))


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    embed(sys.argv[1], sys.argv[2])
    return 0


if __name__ == "__main__":
    sys.exit(main())
