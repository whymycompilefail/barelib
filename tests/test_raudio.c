static void test_LoadWaveFromMemory(void)
{
    TEST_SECTION("LoadWaveFromMemory");

    // Load a valid WAV from memory
    Wave wave = LoadWaveFromMemory(".wav", testWavData, sizeof(testWavData));
    TEST("LoadWaveFromMemory returns valid wave", IsWaveValid(wave));
    TEST("Wave frameCount > 0", wave.frameCount > 0);
    TEST("Wave sampleRate == 44100", wave.sampleRate == 44100);
    TEST("Wave channels == 1", wave.channels == 1);
    TEST("Wave sampleSize == 16", wave.sampleSize == 16);
    TEST("Wave data != NULL", wave.data != NULL);
    UnloadWave(wave);

    // Test with NULL data
    Wave emptyWave = LoadWaveFromMemory(".wav", NULL, 0);
    TEST("LoadWaveFromMemory with NULL returns invalid", !IsWaveValid(emptyWave));

    // Test with invalid extension
    Wave invalidWave = LoadWaveFromMemory(".xyz", testWavData, sizeof(testWavData));
    TEST("LoadWaveFromMemory with unknown extension returns invalid", !IsWaveValid(invalidWave));
}

static void test_IsWaveValid(void)
{
    TEST_SECTION("IsWaveValid");

    // Create a zero-initialized wave (invalid)
    Wave invalidWave = { 0 };
    TEST("Zero-initialized wave is invalid", !IsWaveValid(invalidWave));

    // Create a valid wave from memory
    Wave wave = LoadWaveFromMemory(".wav", testWavData, sizeof(testWavData));
    TEST("Loaded wave is valid", IsWaveValid(wave));
    UnloadWave(wave);
}

